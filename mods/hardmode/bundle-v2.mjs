import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
if (!process.argv[2]) throw new Error('Pass the browser dist directory.');
const browser = resolve(process.argv[2]);
const emitted = new Map();
const modules = [];

function bundle(path) {
  if (emitted.has(path)) {
    const module = emitted.get(path);
    if (!module.ready) throw new Error(`Cyclic module dependency at ${path}`);
    return module.name;
  }
  const module = { name: `_module${emitted.size}`, ready: false };
  emitted.set(path, module);
  let source = readFileSync(path, 'utf8');
  source = source.replace(/^import\s+\{([\s\S]*?)\}\s+from\s+'([^']+)';[ \t]*$/gm, (_, names, specifier) => {
    if (!specifier.startsWith('@browser/') && !specifier.startsWith('.')) throw new Error(`Unsupported import ${specifier}`);
    const dependency = specifier.startsWith('@browser/') ? resolve(browser, specifier.slice(9)) : resolve(dirname(path), specifier);
    return `const {${names.replace(/\s+as\s+/g, ': ')}} = ${bundle(dependency)};`;
  });
  const exports = [];
  source = source.replace(/^export (const|let|function|class) ([\w$]+)/gm, (_, kind, name) => {
    exports.push(name);
    return `${kind} ${name}`;
  });
  source = source.replace(/^export\s+\{([^}]+)\};[ \t]*$/gm, (_, names) => {
    for (const name of names.split(',')) {
      const [local, alias] = name.trim().split(/\s+as\s+/);
      exports.push(alias ? `${alias}: ${local}` : local);
    }
    return '';
  });
  if (/^(import\s|export\s)/m.test(source)) throw new Error(`Unsupported module declaration in ${path}`);
  modules.push(`const ${module.name} = (() => {\n${source}\nreturn {${exports.join(',')}};\n})();`);
  module.ready = true;
  return module.name;
}

bundle(resolve(here, 'v2-entry.mjs'));
const prelude = `// Generated by mods/hardmode/bundle-v2.mjs from the V2 browser engine.\n'use strict';\n` +
  `if (!globalThis.structuredClone) globalThis.structuredClone = value => value === undefined ? undefined : JSON.parse(JSON.stringify(value));\n`;
writeFileSync(resolve(here, '../../emulator/src/hunter_ai_model.js'), prelude + modules.join('\n') + '\n');
